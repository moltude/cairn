"""Convert the owner's styled CalTopo test map (tests/fixtures/caltopo-random/) through
Cairn in all three formats and report parity, reusing scripts/dark_divide_parity.py.

    uv run python scripts/caltopo_random_parity.py

Writes tests/fixtures/caltopo-random/cairn_output/from_<format>/ and PARITY.md.
Deterministic; tests/test_caltopo_random_parity.py fails on drift.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIX = ROOT / "tests" / "fixtures" / "caltopo-random"
STEM = "onx-test-random"

_spec = importlib.util.spec_from_file_location("dark_divide_parity", ROOT / "scripts" / "dark_divide_parity.py")
parity = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(parity)


def configure(out: Path | None = None, report: Path | None = None) -> None:
    parity.FIX, parity.SRC, parity.STEM = FIX, FIX, STEM
    parity.INPUTS = {"geojson": f"{STEM}.json", "gpx": f"{STEM}.gpx", "kml": f"{STEM}.kml"}
    parity.OUT = out or FIX / "cairn_output"
    parity.REPORT = report or FIX / "PARITY.md"


def run() -> dict:
    return {tag: parity.convert(tag) for tag in parity.INPUTS}


def report(results: dict) -> str:
    lines = [
        "# caltopo-random: format parity report",
        "",
        "Generated by `scripts/caltopo_random_parity.py`. Do not edit by hand.",
        "",
        "The owner's styled CalTopo test map (2026-10-22): built-in symbols with colors, a solid,",
        "a long-dash and an arrow line with different widths and opacities, and a filled area, in",
        "no folder. Exported as GeoJSON, GPX and KML; each loaded through Cairn with no edits.",
        "",
        "## Review screen per format",
        "",
        "| Format | Kind | Name | Icon | Color | Note |",
        "|---|---|---|---|---|---|",
    ]
    for tag, (review, *_r) in results.items():
        for kind in ("waypoints", "tracks", "shapes"):
            for i in review[kind]:
                note = (i.get("desc") or "").replace("\n", "⏎")
                lines.append(f"| {tag} | {kind} | {i['name']} | {i['icon'] or '—'} | {i['color']} | {note} |")
    ref, gref = results["geojson"][0], results["geojson"][1]
    lines += ["", "## Cross-format differences (GeoJSON is the reference)", ""]
    for tag in ("kml", "gpx"):
        d = parity._diff(ref, results[tag][0], gref, results[tag][1], parity.CROSS_FIELDS)
        lines.append(f"### geojson vs {tag}: {'identical' if not d else f'{len(d)} difference(s)'}")
        lines += [f"- {x}" for x in d] + [""]
    lines += ["## Review screen vs re-read export", ""]
    for tag, (review, rgeo, reread, egeo) in results.items():
        d = parity._diff(review, reread, rgeo, egeo)
        lines.append(f"### {tag}: {'identical' if not d else f'{len(d)} difference(s)'}")
        lines += [f"- {x}" for x in d] + [""]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    configure()
    text = report(run())
    parity.REPORT.write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
